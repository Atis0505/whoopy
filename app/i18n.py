def normalize_lang(lang: str | None) -> str:
    lang = (lang or "hu").lower().strip()
    return lang if lang in SUPPORTED_LANGS else "hu"


def t(lang: str, key: str) -> str:
    lang = normalize_lang(lang)
    return TRANSLATIONS.get(lang, TRANSLATIONS["hu"]).get(key) or TRANSLATIONS["hu"].get(key, key)
